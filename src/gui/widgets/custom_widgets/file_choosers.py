class FolderChooserButton:
    """ Class doc """
    
    def __init__ (self, main = None, sel_type = 'folder', home  = None, parent = None):
        """ Class initialiser """
        self.main     =  main
        self.btn      =  Gtk.Button()
        self.sel_type =  sel_type # file/folder
        
        
        if parent:
            self.parent = parent
        else:
            self.parent =  self.main.window
        
        #self.sel_type = 'file' # file/folder

        grid = Gtk.Grid ()
        grid.set_column_spacing (10)
        img = Gtk.Image()
        img.set_from_file(os.path.join(self.main.home,'src/gui/icons/icon_open.png'))
        self.label = Gtk.Label(label='...')
        self.btn.connect('clicked', self.open_filechooser)

        grid.attach (img, 0, 0, 1, 1)
        grid.attach (self.label, 1, 0, 1, 1)
        self.btn.set_child(grid)
        #return self.btn 
        
        self.folder = None
        if home:
            self.set_folder ( folder = home)
        
        self.set_tooltop('The working directory is where EasyHybrid suggests saving any files generated by the simulation routines. This is a dynamic variable that can be easily changed at any time while using the interface.')
    #====================================================================================
    def set_folder (self, folder = '/home'):
        """ Function doc """
        if folder == None:
            self.folder = os.environ.get('HOME')
        else:
            self.folder = folder
        dprint( self.folder)
        name = os.path.basename(self.folder )
        #print( name)
        self.label.set_text(name)
        return self.folder
        #self.main.pdynamo_session.systems[self.main.pdynamo_session.active_id]['working_folder'] = self.folder
    #====================================================================================
    def get_folder (self):
        """ Function doc """
        return self.folder
        
    #====================================================================================    
    def open_filechooser (self, parent = None):
        """Ask for a folder (or a file, when sel_type is 'file')."""
        if self.sel_type == 'folder':
            mode, title = file_dialogs.SELECT_FOLDER, "Please choose a folder"
        else:
            mode, title = file_dialogs.OPEN, "Please choose a file"

        def on_selected(path):
            if path:
                self.set_folder(folder=path)
            else:
                dprint("Cancel clicked")

        file_dialogs.choose_file(
            self.parent, on_selected, mode=mode, title=title,
            initial_path=self.folder or self.main.home,
        )

    def set_tooltop (self, text = ''):
        """ Function doc """
        self.btn.set_tooltip_text(text)


class FileChooser:
    """ Class doc """
    
    def __init__ (self, main_window = None , easyhybrid = False):
        """ Class initialiser """
        self.main_window = main_window
        self.easyhybrid = easyhybrid 

    def open(self, callback, select_multiple=False, filters=None):
        """Ask for one or more files; the callback gets a path or a list."""
        main = self.main_window.window if self.main_window is not None else None
        search_folder = getattr(self.main_window, 'current_search_folder', None)
        if not filters:
            filters = [file_dialogs.file_filter("All files", "*")]

        def on_selected(selection):
            selected = selection if select_multiple else ([selection] if selection else [])
            if selected and self.main_window is not None:
                self.main_window.current_search_folder = os.path.dirname(selected[0])
            callback(selection)

        file_dialogs.choose_file(
            main, on_selected, title="Open File...",
            mode=file_dialogs.OPEN_MULTIPLE if select_multiple else file_dialogs.OPEN,
            initial_path=search_folder, filters=filters,
        )
